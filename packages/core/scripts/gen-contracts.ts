// Generates typed ABIs and creation bytecode from the Foundry build and the EAS package.
//
// Vault-type files are frozen: validation rebuilds every vault's CREATE2 address from this code,
// so changing it would make existing vaults fail. A rebuild that produces different bytecode for an
// existing type is an error; new code needs a new type ID (e.g. lido-wsteth-v2).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

type AbiItem = { type: string; name?: string; inputs?: { type: string }[] }
type Artifact = { abi: AbiItem[]; bytecode: string }

const coreDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(coreDir, '../../contracts/out')
const easDir = join(
  dirname(createRequire(import.meta.url).resolve('@ethereum-attestation-service/eas-contracts/package.json')),
  'artifacts/contracts',
)
const generatedDir = join(coreDir, 'src/generated')

function forgeArtifact(contract: string): Artifact {
  const json = JSON.parse(readFileSync(join(outDir, `${contract}.sol/${contract}.json`), 'utf8'))
  return { abi: json.abi, bytecode: json.bytecode.object }
}

function hardhatArtifact(contract: string): Artifact {
  const json = JSON.parse(readFileSync(join(easDir, `${contract}.sol/${contract}.json`), 'utf8'))
  return { abi: json.abi, bytecode: json.bytecode }
}

function signature(item: AbiItem): string {
  return `${item.type}:${item.name ?? ''}(${(item.inputs ?? []).map((i) => i.type).join(',')})`
}

/// LidoStrategy forwards unknown calls to the shared implementation, so the vault's ABI is both,
/// deduplicated by signature (as Octant's script/combine-proxy-abis.sh does).
export function mergeAbis(...abis: AbiItem[][]): AbiItem[] {
  const seen = new Map<string, AbiItem>()
  for (const item of abis.flat()) {
    if (item.type === 'constructor' || item.type === 'fallback' || item.type === 'receive') continue
    if (!seen.has(signature(item))) seen.set(signature(item), item)
  }
  return [...seen.values()]
}

/// Throws if a frozen vault type would get different bytecode.
export function assertFrozen(kind: string, existing: Record<string, string>, next: Record<string, string>) {
  for (const [name, bytecode] of Object.entries(next)) {
    if (existing[name] !== undefined && existing[name] !== bytecode) {
      throw new Error(
        `${kind} is frozen, but the rebuilt ${name} bytecode differs. Existing vaults would stop validating; ` +
          `add a new vault type instead of changing this one.`,
      )
    }
  }
}

function constant(name: string, value: unknown): string {
  return `export const ${name} = ${JSON.stringify(value, null, 2)} as const\n`
}

const header = '// Generated by packages/core/scripts/gen-contracts.ts. Do not edit.\n\n'

function writeCommon() {
  const eas = hardhatArtifact('EAS')
  const registry = hardhatArtifact('SchemaRegistry')
  const body = [
    constant('easAbi', eas.abi),
    constant('easBytecode', eas.bytecode),
    constant('schemaRegistryAbi', registry.abi),
    constant('schemaRegistryBytecode', registry.bytecode),
  ].join('\n')
  writeFileSync(join(generatedDir, 'common.ts'), header + body)
}

async function writeLidoWstethV1() {
  const kind = 'lido-wsteth-v1'
  const strategy = forgeArtifact('LidoStrategy')
  const implementation = forgeArtifact('YieldSkimmingTokenizedStrategy')
  const forwarder = forgeArtifact('YieldForwarder')
  const trigger = forgeArtifact('PayoutTrigger')
  const bytecodes = {
    vaultBytecode: strategy.bytecode,
    implementationBytecode: implementation.bytecode,
    forwarderBytecode: forwarder.bytecode,
    payoutTriggerBytecode: trigger.bytecode,
  }

  const file = join(generatedDir, 'kinds', `${kind}.ts`)
  if (existsSync(file)) {
    const existing = (await import(file)) as Record<string, string>
    assertFrozen(kind, existing, bytecodes)
    console.log(`${kind}: frozen and unchanged`)
    return
  }

  const body = [
    constant('meta', { kind, octant: '1.3.0 (06ae2b9fa2e4443a3d9f6148498d4ada4f9861e8)', solc: '0.8.33' }),
    constant('vaultAbi', mergeAbis(strategy.abi, implementation.abi)),
    // Constructor only, for encoding deployments.
    constant('vaultDeployAbi', strategy.abi.filter((i) => i.type === 'constructor')),
    constant('forwarderAbi', forwarder.abi),
    constant('payoutTriggerAbi', trigger.abi),
    ...Object.entries(bytecodes).map(([name, value]) => constant(name, value)),
  ].join('\n')
  writeFileSync(file, header + body)
  console.log(`${kind}: written`)
}

/// Not frozen: the router isn't part of any vault's address, so a new build may be redeployed.
function writeDepositRouter() {
  const router = forgeArtifact('DepositRouter')
  const body = [constant('depositRouterAbi', router.abi), constant('depositRouterBytecode', router.bytecode)].join('\n')
  writeFileSync(join(generatedDir, 'deposit-router.ts'), header + body)
}

if (import.meta.main) {
  mkdirSync(join(generatedDir, 'kinds'), { recursive: true })
  writeCommon()
  writeDepositRouter()
  await writeLidoWstethV1()
}
